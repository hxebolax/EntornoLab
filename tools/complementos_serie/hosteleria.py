def _forma_futbolin() -> c.Forma:
	"""Futbolín: la caja del campo y cuatro barras que la atraviesan y sobresalen por los dos lados."""
	barras = (0.14, 0.38, 0.62, 0.86)
	puntos: list[tuple[float, float]] = [(0.0, 0.2)]
	for x in barras:
		puntos += [(x - 0.02, 0.2), (x - 0.02, 0.0), (x + 0.02, 0.0), (x + 0.02, 0.2)]
	puntos += [(1.0, 0.2), (1.0, 0.8)]
	for x in reversed(barras):
		puntos += [(x + 0.02, 0.8), (x + 0.02, 1.0), (x - 0.02, 1.0), (x - 0.02, 0.8)]
	puntos.append((0.0, 0.8))
	return c.poligono(
		puntos,
		"una caja alargada con cuatro barras que sobresalen por delante y por detrás",
		"a long box with four rods sticking out at the front and at the back",
	)


def _forma_butaca_cubo() -> c.Forma:
	"""Butaca de cubo: respaldo redondo que abraza por detrás y frente recto."""
	puntos: list[tuple[float, float]] = [(0.0, 1.0)]
	puntos += [(0.5 + 0.5 * math.cos(math.pi + math.pi * k / 8), 0.45 + 0.45 * math.sin(math.pi + math.pi * k / 8)) for k in range(9)]
	puntos.append((1.0, 1.0))
	return c.poligono(puntos, "un respaldo redondo por detrás y un frente recto", "a round back and a straight front")


