def _dos_bloques(bloque: float, barra: float, es: str, en: str) -> c.Forma:
	"""Dos cuerpos en los extremos unidos por una barra fina centrada (una barra con discos, dos postes con su listón)."""
	a, b = 0.5 - barra / 2, 0.5 + barra / 2
	puntos = [
		(0, 0),
		(bloque, 0),
		(bloque, a),
		(1 - bloque, a),
		(1 - bloque, 0),
		(1, 0),
		(1, 1),
		(1 - bloque, 1),
		(1 - bloque, b),
		(bloque, b),
		(bloque, 1),
		(0, 1),
	]
	return c.poligono(puntos, es, en)


