def _fila_de_vallas(pies: int, grosor: float = 0.05) -> c.Forma:
	"""Barra larga y fina con pies planos que la cruzan y sobresalen por delante y por detrás."""
	margen = 0.04
	paso = (1.0 - 2 * margen - grosor) / (pies - 1)
	inicios = [margen + k * paso for k in range(pies)]
	puntos: list[tuple[float, float]] = [(0.0, 0.42)]
	for x0 in inicios:
		puntos += [(x0, 0.42), (x0, 0.0), (x0 + grosor, 0.0), (x0 + grosor, 0.42)]
	puntos += [(1.0, 0.42), (1.0, 0.58)]
	for x0 in reversed(inicios):
		puntos += [(x0 + grosor, 0.58), (x0 + grosor, 1.0), (x0, 1.0), (x0, 0.58)]
	puntos.append((0.0, 0.58))
	return c.poligono(
		puntos,
		"una barra larga y fina con pies que la cruzan y sobresalen a los dos lados",
		"a long thin bar with feet crossing it and sticking out on both sides",
	)


