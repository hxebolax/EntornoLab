def _hache(pie: float, alma: float, es: str, en: str) -> c.Forma:
	"""Dos cuerpos en los extremos unidos por una banda fina centrada: dos postes con su cordón, un panel con sus pies."""
	a, b = 0.5 - alma / 2, 0.5 + alma / 2
	return c.poligono(
		[(0, 0), (pie, 0), (pie, a), (1 - pie, a), (1 - pie, 0), (1, 0), (1, 1), (1 - pie, 1), (1 - pie, b), (pie, b), (pie, 1), (0, 1)],
		es,
		en,
	)


def _u_trasera(lado: float, frente: float, es: str, en: str) -> c.Forma:
	"""U abierta por detrás: un frente grueso delante y dos costados finos que van hacia la pared."""
	return c.poligono([(0, 0), (lado, 0), (lado, 1 - frente), (1 - lado, 1 - frente), (1 - lado, 0), (1, 0), (1, 1), (0, 1)], es, en)


