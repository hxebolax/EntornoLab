def _u_atras(lado: float, frente: float) -> list[c.Punto]:
	"""Puntos de una U abierta por detrás: un frente y dos costados que van hacia la pared."""
	return [(0, 0), (lado, 0), (lado, 1 - frente), (1 - lado, 1 - frente), (1 - lado, 0), (1, 0), (1, 1), (0, 1)]


def _t_frente(tallo: float, cabeza: float) -> list[c.Punto]:
	"""Puntos de una te invertida: un cuerpo estrecho detrás y una barra ancha delante."""
	a, b = 0.5 - tallo / 2, 0.5 + tallo / 2
	return [(a, 0), (b, 0), (b, 1 - cabeza), (1, 1 - cabeza), (1, 1), (0, 1), (0, 1 - cabeza), (a, 1 - cabeza)]


