def _cierra_sola(segundos: int, sonido: str | None = None) -> dict[str, Any]:
	"""Dinámica de una puerta con muelle o con motor: abierta, se cierra ella sola al cabo de ``segundos``."""
	dinamica: dict[str, Any] = {"tipo": "temporizador", "estado": "abierto", "segundos": segundos, "al_terminar": "cerrado"}
	if sonido:
		dinamica["sonido_al_terminar"] = sonido
	return dinamica


