def _fila_redonda(cuantos: int, es: str, en: str) -> c.Forma:
	"""Fila de cuerpos redondos pegados unos a otros (orinales, cojines): un contorno festoneado."""
	radio = 0.5 / cuantos
	arriba: list[c.Punto] = []
	abajo: list[c.Punto] = []
	for k in range(cuantos):
		centro = (2 * k + 1) * radio
		for paso in range(7):
			angulo = math.radians(150 - 20 * paso)
			x = centro + radio * math.cos(angulo) / math.cos(math.radians(30))
			if paso == 0 and k > 0:
				continue
			arriba.append((x, 0.5 - 0.5 * math.sin(angulo)))
			abajo.append((x, 0.5 + 0.5 * math.sin(angulo)))
	return c.poligono(arriba + abajo[::-1], es, en)


def _flor(petalos: int = 6, pasos: int = 36) -> list[c.Punto]:
	"""Contorno lobulado: un círculo con entrantes entre pétalo y pétalo."""
	puntos: list[c.Punto] = []
	for k in range(pasos):
		angulo = 2 * math.pi * k / pasos
		radio = 0.8 + 0.2 * math.cos(petalos * angulo)
		puntos.append((radio * math.cos(angulo), radio * math.sin(angulo)))
	return puntos


